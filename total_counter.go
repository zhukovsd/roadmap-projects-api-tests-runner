package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"maps"
	"os"
	"slices"
	"strings"

	"github.com/zhukovsd/roadmap-projects-api-test-runner/internal/logger"
	"golang.org/x/tools/go/packages"
)

var constantOfPkg = map[string]string{
	"currencyexchange_test": "currencyExchangeTotal",
}

func main() {
	cfg := &packages.Config{
		Mode:  packages.LoadSyntax,
		Tests: true,
		Fset:  token.NewFileSet(),
	}

	pkgs, err := packages.Load(cfg, "../tests/...")
	if err != nil {
		logger.Error(err.Error())
		return
	}

	constants := make(map[string]int)
	for _, pkg := range pkgs {
		pkgAsserts := 0
		for _, file := range pkg.Syntax {
			pos := pkg.Fset.Position(file.Pos())
			asserts, err := countAssertExecutions(file, pkg)
			if err != nil {
				logger.Error(err.Error())
				continue
			}
			pkgAsserts += asserts
			logger.Info("File total asserts ", "total", asserts, "file", pos.Filename)
		}

		if constName, found := constantOfPkg[pkg.Name]; found && pkgAsserts > 0 {
			logger.Info("Package total asserts", "total", pkgAsserts, "package", pkg.Name)
			constants[constName] = pkgAsserts
		}
	}

	writeFile(constants)
}

func writeFile(constants map[string]int) {
	logger.Info("Trying to generate", "constants", constants)

	var b strings.Builder
	b.WriteString("// Code generated by gen; DO NOT EDIT.\n\npackage internal\n\nconst (\n")
	for _, k := range slices.Sorted(maps.Keys(constants)) {
		fmt.Fprintf(&b, "\t%s = %d\n", k, constants[k])
	}
	b.WriteString(")\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		logger.Error(err.Error())
		panic(err)
	}

	if err := os.WriteFile("../internal/test_constants.go", src, 0644); err != nil {
		logger.Error(err.Error())
		panic(err)
	}
	logger.Info("Generated internal/test_constants.go")
}

func countAssertExecutions(file *ast.File, pkg *packages.Package) (int, error) {
	multipliers := make(map[*ast.CallExpr]int)

	ast.Inspect(file, func(n ast.Node) bool {
		loop, ok := n.(*ast.RangeStmt)
		if !ok {
			return true
		}

		iterations, ok := iterationCount(loop.X, pkg)
		if !ok {
			return true
		}

		ast.Inspect(loop.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if ok && isAssertCall(call) {
				multipliers[call] = iterations
			}
			return true
		})

		return true
	})

	total := 0
	ast.Inspect(file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || !isAssertCall(call) {
			return true
		}

		multiplier, insideLoop := multipliers[call]
		if !insideLoop {
			multiplier = 1
		}

		total += multiplier
		return true
	})

	return total, nil
}

func isAssertCall(call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "assert"
}

func iterationCount(expr ast.Expr, pkg *packages.Package) (int, bool) {
	switch expr := expr.(type) {
	case *ast.CompositeLit:
		return len(expr.Elts), true

	case *ast.Ident:
		obj := pkg.TypesInfo.Uses[expr]
		if obj == nil {
			return 0, false
		}

		return findCompositeLiteral(obj, pkg.Syntax, pkg.TypesInfo)
	}

	return 0, false
}

func findCompositeLiteral(obj types.Object, files []*ast.File, info *types.Info) (int, bool) {
	found := -1
	for _, file := range files {

		ast.Inspect(file, func(n ast.Node) bool {
			switch n := n.(type) {
			// const or var declaration
			case *ast.ValueSpec:
				for i, identifier := range n.Names {
					if info.Defs[identifier] != obj || i >= len(n.Values) {
						continue
					}

					if lit, ok := n.Values[i].(*ast.CompositeLit); ok {
						found = len(lit.Elts)
						return true
					}
				}

			case *ast.AssignStmt:
				if n.Tok != token.DEFINE {
					return true
				}

				for i, lhs := range n.Lhs {
					identifier, ok := lhs.(*ast.Ident)
					if !ok || info.Defs[identifier] != obj || i >= len(n.Rhs) {
						continue
					}

					if lit, ok := n.Rhs[i].(*ast.CompositeLit); ok {
						found = len(lit.Elts)
						return true
					}
				}
			}

			return true
		})
	}

	return found, found > 0
}
